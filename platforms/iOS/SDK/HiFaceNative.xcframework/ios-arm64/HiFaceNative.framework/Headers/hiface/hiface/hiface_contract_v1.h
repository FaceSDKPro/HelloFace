/*
 * 特征文本形式。宿主保存的是**字符串**，不是 float 数组。因此「怎么把特征变成字符串」和
 * 「哪些字符串是合法的」都必须是 ABI 的一部分：Android 录入的文本要能在 iOS 上验证，
 * 任何一端自己拼一遍前缀和 Base64，差异都不会在编译期暴露，只会在跨端验证失败时才出现。
 *
 * HF1 格式（长度固定）：
 *   "HF1:" + Base64URL(450 字节 Q7 payload)，共 604 字符，不含补位，也不加密。
 *   "HF" = HiFace Feature，"1" = 序列化协议版本 1；模型/预处理兼容性由
 *   HIFACE_FEATURE_SPACE_ID 单独标识。正式发布后保留 V1 编码和特征空间语义，
 *   SDK 版本升级不改变已录入特征的解释方式。
 *
 * 解码只接受 Base64URL 字母表（A-Z a-z 0-9 - _），拒绝 '='、空白和其他任何字符，
 * 并要求整串长度精确等于 HIFACE_FEATURE_TEXT_LENGTH。
 */

/* 不含结尾 '\0' 的字符数。 */
#define HIFACE_FEATURE_TEXT_LENGTH 604u

/* 传给 hiface_feature_encode_text_v1 的缓冲区最小容量（含结尾 '\0'）。 */
#define HIFACE_FEATURE_TEXT_BUFFER_SIZE 605u

#define HIFACE_FEATURE_TEXT_PREFIX "HF1:"

/* 当前识别模型及五点对齐/归一化契约的兼容标识；不等同于 HF1 序列化格式。 */
#define HIFACE_FEATURE_SPACE_ID "hiface-feature-new-v1"

